ERRS = []
def ok(cond, msg):
    print(('PASS ' if cond else 'FAIL ') + msg)
    if not cond: ERRS.append(msg)

async def text(page):
    return await page.evaluate("document.getElementById('view').innerText")

async def shot(page, name, full=True):
    await page.screenshot(path=os.path.join(SHOTS, name + '.png'), full_page=full)

async def no_markers(page, where):
    t = await page.evaluate("document.body.innerText + [].map.call(document.querySelectorAll('[placeholder],[aria-label]'),function(e){return (e.getAttribute('placeholder')||'')+(e.getAttribute('aria-label')||'')}).join(' ')")
    ok('⟨' not in t and '⟩' not in t, 'no raw gender markers on ' + where)

async def click_text(page, sel, txt):
    await page.locator(sel, has_text=txt).first.click()

async def enter_parent(page):
    await page.click('#footParent')
    await page.wait_for_selector('#pinIn, .ph-top')
    if await page.locator('#pinIn').count():
        await page.fill('#pinIn', '1234'); await page.click('#pinForm button[type=submit]')
        await page.wait_for_selector('.ph-top')

